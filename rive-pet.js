// Ria, the third mascot (Nov 19 2026): an original pixel-art girl (teal hair,
// lavender hoodie) rigged with Polymation's free trial and played through
// Rive's free canvas runtime (@rive-app/canvas-single, vendored as
// rive-canvas.js - the wasm ships inlined, so nothing is fetched).
//
// Her baked relay-girl.riv has one 'Puppet' state machine with a single
// number input named 'animation': 0 idle, 1 walk, 2 wave, 3 cheer. That is
// her WHOLE clip set - richer pet states (sit, sleep, drag, reactions...)
// map onto the closest of the four instead of silently freezing on a
// missing sprite, the same spirit as mascot-anims.cjs DEX_FALLBACK.
//
// The pet page is a file:// page and Chromium blocks fetch()/XHR to file://
// URLs, so the .riv bytes arrive as base64 in relay-girl-riv.js
// (window.RELAY_GIRL_RIV_B64, generated by tools/embed-riv.cjs).
//
// UMD like pet-behavior.cjs: the renderer loads it as a script, tests
// require() it.
(function (root) {
  const NUMS = { idle: 0, walk: 1, wave: 2, cheer: 3 };
  // One-shot clips return to idle after their baked length (30 fps bake):
  // wave is 52 frames (~1.7 s), cheer 24 frames (~0.8 s); small margin so
  // the clip is never visibly cut. Idle and walk loop until the next state.
  const HOLD_MS = { wave: 1900, cheer: 1000 };
  // App state -> Rive clip. Movement plays walk, greetings wave, success
  // and celebration cheer; everything else (sit, sleep, thinking, taps,
  // falls, ambient beats) is a quiet idle - she has no art for it yet.
  const MAP = {
    walk: 'walk', run: 'walk', leap: 'walk', drag: 'walk',
    wave: 'wave', landing: 'wave', bow: 'wave',
    cheer: 'cheer', celebrate: 'cheer', gesture: 'cheer', emote: 'cheer',
    'react-success': 'cheer', 'react-idea': 'cheer',
  };
  function mapState(name) { return MAP[name] || 'idle'; }

  let rive = null, input = null, canvas = null, current = 'idle', timer = null, loading = false;

  function apply(clip) {
    current = clip;
    if (!input) return;
    input.value = NUMS[clip];
    clearTimeout(timer);
    if (HOLD_MS[clip]) timer = setTimeout(() => {
      if (current === clip && input) { current = 'idle'; input.value = NUMS.idle; }
    }, HOLD_MS[clip]);
  }

  // name: a requested PET state ('idle', 'walk', 'touch-head', 'sit', ...).
  function setState(name) { apply(mapState(name)); }

  function init(cv) {
    canvas = cv;
    if (rive) {rive.play();return Promise.resolve(true);}
    if (loading) return Promise.resolve(false);
    if (!root.rive || !root.RELAY_GIRL_RIV_B64) return Promise.resolve(false);
    loading = true;
    try {
      if (root.rive.Rive && root.rive.Rive.suppressDeprecationWarnings) root.rive.Rive.suppressDeprecationWarnings = ['state-machine-inputs'];
      const bin = atob(root.RELAY_GIRL_RIV_B64);
      const bytes = new Uint8Array(bin.length);
      for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
      rive = new root.rive.Rive({
        buffer: bytes.buffer,
        canvas: cv,
        stateMachine: 'Puppet',
        autoplay: true,
        layout: new root.rive.Layout({ fit: root.rive.Fit.Contain, alignment: root.rive.Alignment.BottomCenter }),
        onLoad: () => {
          try {
            rive.resizeDrawingSurfaceToCanvas();
            const ins = rive.stateMachineInputs('Puppet') || [];
            input = ins.find((i) => i.name === 'animation') || null;
            if (input) apply(current);
          } catch (e) { /* a lost input leaves her idling, never a crash */ }
        },
        onLoadError: () => { rive = null; input = null; },
      });
    } catch (e) {
      rive = null;
    }
    loading = false;
    return Promise.resolve(!!rive);
  }

  function resize() { if (rive) try { rive.resizeDrawingSurfaceToCanvas(); } catch (e) {} }
  function cleanup() { clearTimeout(timer); if (rive) try { rive.cleanup(); } catch (e) {} rive = null; input = null; }

  function pause(){clearTimeout(timer);if(rive)rive.pause();}
  function resume(){if(rive)rive.play();}
  const api = { pause, resume, init, setState, mapState, resize, cleanup, NUMS, HOLD_MS, MAP };
  root.RivePet = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
